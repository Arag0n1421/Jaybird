create or replace function public.jaybird_on_task_posted()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_creator text; v_key text; v_payload jsonb;
begin
  if new.created_by is null or new.status not in('open','asked') then return new; end if;
  select name into v_creator from public.members where id=new.created_by;
  v_key:='task_created:'||new.id;
  v_payload:=jsonb_build_object('task_id',new.id,'project_id',new.project_id,'created_by',new.created_by,
    'creator_name',v_creator,'title',new.title);
  insert into public.news(chapter_id,type,member_id,project_id,text,event_key)
  values(new.chapter_id,'task_posted',new.created_by,new.project_id,
    v_creator||' posted a task: '||new.title,v_key) on conflict(event_key) do nothing;
  -- UNION deduplicates a member who both follows the creator and is a buddy.
  insert into public.notifications(member_id,type,event_key,payload)
  select r.member_id,'task_posted',v_key,v_payload from (
    select follower_id as member_id from public.follows where followee_id=new.created_by
    union select buddy_id from public.buddies where new_member_id=new.created_by
    union select new_member_id from public.buddies where buddy_id=new.created_by
  ) r where r.member_id<>new.created_by
  on conflict(member_id,event_key) do nothing;
  return new;
end $$;
