-- Peer-recognition business rules; SECURITY INVOKER throughout.
-- Demo actor inputs are not an authentication boundary. Existing open ledger
-- access permits non-peer demo XP edits; production auth/RLS is separate work.

create or replace function public.peer_badge_allowance(p_member bigint,p_season int default null)
returns table(tier text,eligible boolean,quota int,used int,remaining int,xp int)
language sql stable security invoker set search_path=pg_catalog,public as $allowance$
  with actor as (
    select m.id,greatest(
      case when s.level >= 3 then 1 else 0 end,
      case when s.level >= 6 or exists(select 1 from public.projects p where p.lead_id=m.id and p.status='closed') then 2 else 0 end,
      case when m.role in ('board','president') then 3 else 0 end,
      case when m.is_senator or m.is_national_board then 4 else 0 end
    ) as unlocked
    from public.members m join public.member_stats s on s.member_id=m.id where m.id=p_member
  ), tiers(tier,ordinal,quota,xp) as (
    values ('bronze'::text,1,5,20),('silver',2,3,60),('gold',3,2,150),('platinum',4,1,300)
  ), usage as (
    select b.tier,count(*)::int as used from public.peer_badges b
      where b.giver_id=p_member and b.season=coalesce(p_season,extract(year from (now() at time zone 'UTC'))::int)
      group by b.tier
  )
  select t.tier,coalesce(a.unlocked,0)>=t.ordinal,t.quota,coalesce(u.used,0),
    greatest(t.quota-coalesce(u.used,0),0),t.xp
    from tiers t left join actor a on true left join usage u on u.tier=t.tier order by t.ordinal
$allowance$;

create or replace function public.jaybird_validate_peer_badge()
returns trigger language plpgsql security invoker set search_path=pg_catalog,public as $validate$
declare v_badge public.badges%rowtype; v_allow record;
begin
  if tg_op <> 'INSERT' then
    raise exception 'Peer-recognition history is immutable' using errcode='23514';
  end if;
  if new.giver_id is null or new.receiver_id is null or new.giver_id=new.receiver_id then
    raise exception 'Choose another member to recognize' using errcode='23514';
  end if;
  -- Global member-id order covers reciprocal awards without lock inversion.
  -- The giver lock serializes annual quota checks, including direct inserts.
  perform m.id from public.members m where m.id in (new.giver_id,new.receiver_id) order by m.id for update;
  if not exists(select 1 from public.members where id=new.giver_id)
    or not exists(select 1 from public.members where id=new.receiver_id) then
    raise exception 'Giver and receiver must exist' using errcode='23503';
  end if;
  new.note:=btrim(new.note);
  if new.note is null or char_length(new.note) not between 1 and 140 then
    raise exception 'Recognition note must contain 1 to 140 characters' using errcode='23514';
  end if;
  new.season:=extract(year from (now() at time zone 'UTC'))::int;
  new.created_at:=now();
  select * into v_badge from public.badges where id=new.badge_id;
  if not found or v_badge.kind<>'peer' or v_badge.tier is null then
    raise exception 'Choose a peer-recognition badge' using errcode='23514';
  end if;
  new.tier:=v_badge.tier;
  if exists(select 1 from public.peer_badges b where b.giver_id=new.giver_id and b.receiver_id=new.receiver_id and b.season=new.season) then
    raise exception 'This member has already been recognized by you this season' using errcode='23505';
  end if;
  select * into v_allow from public.peer_badge_allowance(new.giver_id,new.season) a where a.tier=new.tier;
  if not v_allow.eligible then
    raise exception 'This recognition tier is locked for the giver' using errcode='23514';
  end if;
  if v_allow.remaining <= 0 then
    raise exception 'This recognition tier has no awards remaining this season' using errcode='23514';
  end if;
  return new;
end $validate$;

drop trigger if exists jaybird_peer_validate on public.peer_badges;
create trigger jaybird_peer_validate before insert or update or delete on public.peer_badges
for each row execute function public.jaybird_validate_peer_badge();

create or replace function public.jaybird_guard_peer_catalogue()
returns trigger language plpgsql security invoker set search_path=pg_catalog,public as $catalogue$
begin
  if (new.kind is distinct from old.kind or new.tier is distinct from old.tier)
    and exists(select 1 from public.peer_badges where badge_id=old.id) then
    raise exception 'A recognition badge with award history cannot change kind or tier' using errcode='23514';
  end if;
  return new;
end $catalogue$;
drop trigger if exists jaybird_peer_catalogue_guard on public.badges;
create trigger jaybird_peer_catalogue_guard before update of kind,tier on public.badges
for each row execute function public.jaybird_guard_peer_catalogue();

create or replace function public.jaybird_guard_peer_reward()
returns trigger language plpgsql security invoker set search_path=pg_catalog,public as $reward_guard$
declare v_award public.peer_badges%rowtype; v_expected int;
begin
  if tg_op<>'INSERT' then
    if old.peer_badge_id is not null or old.reason in ('peer_badge_received','peer_badge_given') then
      raise exception 'Peer-recognition XP history is immutable' using errcode='23514';
    end if;
    if tg_op='DELETE' then return old; end if;
    if new.peer_badge_id is not null or new.reason in ('peer_badge_received','peer_badge_given') then
      raise exception 'Peer-recognition XP can only be created by an award' using errcode='23514';
    end if;
    return new;
  end if;
  if new.peer_badge_id is null and new.reason not in ('peer_badge_received','peer_badge_given') then return new; end if;
  if pg_trigger_depth()<2 then
    raise exception 'Peer-recognition XP can only be created by an award' using errcode='23514';
  end if;
  select * into v_award from public.peer_badges where id=new.peer_badge_id;
  if not found then raise exception 'Peer award does not exist' using errcode='23503'; end if;
  v_expected:=case v_award.tier when 'bronze' then 20 when 'silver' then 60 when 'gold' then 150 when 'platinum' then 300 end;
  if new.task_id is not null or new.created_at<>v_award.created_at or new.season<>v_award.season
    or not (
      (new.reason='peer_badge_received' and new.member_id=v_award.receiver_id and new.xp=v_expected)
      or (new.reason='peer_badge_given' and new.member_id=v_award.giver_id and new.xp=5)
    ) then
    raise exception 'Invalid peer-recognition XP reward' using errcode='23514';
  end if;
  return new;
end $reward_guard$;
drop trigger if exists zz_jaybird_peer_reward_guard on public.xp_ledger;
create trigger zz_jaybird_peer_reward_guard before insert or update or delete on public.xp_ledger
for each row execute function public.jaybird_guard_peer_reward();

create or replace function public.jaybird_emit_peer_badge()
returns trigger language plpgsql security invoker set search_path=pg_catalog,public as $emit$
declare v_xp int; v_giver_name text; v_receiver_name text; v_chapter bigint; v_badge_name text; v_key text;
begin
  v_xp:=case new.tier when 'bronze' then 20 when 'silver' then 60 when 'gold' then 150 when 'platinum' then 300 end;
  v_key:='peer_badge:'||new.id;
  insert into public.xp_ledger(member_id,peer_badge_id,xp,reason,season,created_at)
    values(new.receiver_id,new.id,v_xp,'peer_badge_received',new.season,new.created_at),
          (new.giver_id,new.id,5,'peer_badge_given',new.season,new.created_at);
  select name into v_giver_name from public.members where id=new.giver_id;
  select name,chapter_id into v_receiver_name,v_chapter from public.members where id=new.receiver_id;
  select name into v_badge_name from public.badges where id=new.badge_id;
  insert into public.notifications(member_id,type,payload,event_key,created_at)
    values(new.receiver_id,'peer_badge_received',jsonb_build_object(
      'peer_badge_id',new.id,'giver_id',new.giver_id,'receiver_id',new.receiver_id,
      'badge_id',new.badge_id,'badge_name',v_badge_name,'tier',new.tier,'note',new.note,'xp',v_xp,'season',new.season),v_key,new.created_at)
    on conflict(member_id,event_key) do nothing;
  insert into public.news(chapter_id,type,member_id,text,event_key,created_at)
    values(v_chapter,'peer_badge',new.receiver_id,
      v_giver_name||' recognized '||v_receiver_name||' with '||v_badge_name||': '||new.note,v_key,new.created_at)
    on conflict(event_key) do nothing;
  return new;
end $emit$;
drop trigger if exists jaybird_peer_emit on public.peer_badges;
create trigger jaybird_peer_emit after insert on public.peer_badges
for each row execute function public.jaybird_emit_peer_badge();

create or replace function public.give_peer_badge(p_giver bigint,p_receiver bigint,p_badge bigint,p_note text)
returns bigint language plpgsql security invoker set search_path=pg_catalog,public as $give$
declare v_existing public.peer_badges%rowtype; v_id bigint; v_season int;
begin
  -- Use the same lock order as direct-insert validation. A repeated identical
  -- intent returns its existing receipt, even if its original quota is now used.
  perform m.id from public.members m where m.id in (p_giver,p_receiver) order by m.id for update;
  v_season:=extract(year from (now() at time zone 'UTC'))::int;
  select * into v_existing from public.peer_badges b
    where b.giver_id=p_giver and b.receiver_id=p_receiver and b.season=v_season;
  if found then
    if v_existing.badge_id=p_badge and v_existing.note=btrim(p_note) then return v_existing.id; end if;
    raise exception 'A different recognition for this member already exists this season' using errcode='23505';
  end if;
  insert into public.peer_badges(giver_id,receiver_id,badge_id,note,tier)
    values(p_giver,p_receiver,p_badge,p_note,'bronze') returning id into v_id;
  return v_id;
end $give$;

