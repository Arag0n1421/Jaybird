-- Preserve every original allowed reason, even if live has additions beyond the
-- recovered baseline. Extend only reason-only CHECKs, never broad row checks.
do $extend_reasons$
declare v record; v_reason_att smallint;
begin
  select attnum into v_reason_att from pg_attribute where attrelid='public.xp_ledger'::regclass and attname='reason';
  for v in select conname,pg_get_expr(conbin,conrelid) as expression
    from pg_constraint where conrelid='public.xp_ledger'::regclass and contype='c'
      and conkey=array[v_reason_att]::smallint[]
  loop
    if position('peer_badge_received' in v.expression)=0 or position('peer_badge_given' in v.expression)=0 then
      execute format('alter table public.xp_ledger drop constraint %I',v.conname);
      execute format('alter table public.xp_ledger add constraint %I check ((%s) or reason in (''peer_badge_received'',''peer_badge_given''))',v.conname,v.expression);
    end if;
  end loop;
  if not exists (select 1 from pg_constraint where conrelid='public.xp_ledger'::regclass and conname='jaybird_peer_reward_source_check') then
    alter table public.xp_ledger add constraint jaybird_peer_reward_source_check check
      ((peer_badge_id is not null) = (reason in ('peer_badge_received','peer_badge_given')));
  end if;
end $extend_reasons$;

