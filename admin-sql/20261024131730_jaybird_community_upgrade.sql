-- One consistent, source-backed project summary for directory/home/detail.
-- participant_ids combines explicit joins, lead and task assignees once.
create or replace view public.project_community_stats with(security_invoker=true) as
with participants as (
  select project_id,member_id from public.project_members
  union select id,lead_id from public.projects where lead_id is not null
  union select project_id,assignee_id from public.tasks where project_id is not null and assignee_id is not null
), team as (
  select project_id,array_agg(member_id order by member_id) as participant_ids,count(*)::integer as participant_count
  from participants group by project_id
), task_counts as (
  select project_id,count(*) filter(where status<>'cancelled')::integer as task_count,
    count(*) filter(where status='done')::integer as tasks_done,
    count(*) filter(where status in('open','asked'))::integer as open_tasks,
    count(*) filter(where status='done' and completed_at>=now()-interval '7 days')::integer as completed_7d,
    count(*) filter(where created_at>=now()-interval '7 days')::integer as posted_7d,
    array_agg(distinct category order by category) filter(where status<>'cancelled') as categories,
    greatest(max(created_at),max(completed_at)) as last_activity_at
  from public.tasks where project_id is not null group by project_id
), joins as (
  select project_id,count(*) filter(where joined_at>=now()-interval '7 days')::integer as joined_7d,max(joined_at) as last_joined_at
  from public.project_members group by project_id
), xp as (
  select t.project_id,sum(l.xp)::bigint as total_xp from public.xp_ledger l join public.tasks t on t.id=l.task_id
  where t.project_id is not null group by t.project_id
), photos as (
  select project_id,count(*)::integer as photo_count from public.project_photos group by project_id
)
select p.id as project_id,coalesce(team.participant_ids,'{}'::bigint[]) as participant_ids,
  coalesce(team.participant_count,0) as participant_count,coalesce(tc.task_count,0) as task_count,
  coalesce(tc.tasks_done,0) as tasks_done,coalesce(tc.open_tasks,0) as open_tasks,
  case when coalesce(tc.task_count,0)=0 then 0 else round(tc.tasks_done::numeric*100/tc.task_count,1) end as progress_pct,
  coalesce(tc.categories,'{}'::text[]) as categories,coalesce(j.joined_7d,0) as joined_7d,
  coalesce(tc.completed_7d,0) as completed_7d,coalesce(tc.posted_7d,0) as posted_7d,
  coalesce(j.joined_7d,0)+coalesce(tc.completed_7d,0)+coalesce(tc.posted_7d,0) as activity_7d,
  greatest(p.created_at,tc.last_activity_at,j.last_joined_at) as last_activity_at,
  coalesce(xp.total_xp,0)::bigint as total_xp,coalesce(ph.photo_count,0) as photo_count
from public.projects p left join team on team.project_id=p.id left join task_counts tc on tc.project_id=p.id
left join joins j on j.project_id=p.id left join xp on xp.project_id=p.id left join photos ph on ph.project_id=p.id;
grant select on public.project_community_stats to anon,authenticated;

