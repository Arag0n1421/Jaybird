create or replace function public.jaybird_on_task_approved()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_last_id bigint; v_xp integer; v_breakdown jsonb; v_ledger_ids bigint[]; v_name text; v_key text; v_payload jsonb;
begin
  if new.status<>'done' or old.status='done' or new.assignee_id is null then return new; end if;
  v_last_id:=coalesce(nullif(current_setting('jaybird.approval_before_'||new.id,true),''),'0')::bigint;
  select coalesce(sum(xp),0)::integer,coalesce(array_agg(id order by id),'{}'::bigint[])
    into v_xp,v_ledger_ids from public.xp_ledger
    where task_id=new.id and member_id=new.assignee_id and id>v_last_id;
  select coalesce(jsonb_object_agg(reason,xp),'{}'::jsonb) into v_breakdown from (
    select reason,sum(xp)::integer as xp from public.xp_ledger
    where task_id=new.id and member_id=new.assignee_id and id>v_last_id group by reason
  ) r;
  select name into v_name from public.members where id=new.assignee_id;
  v_key:='task_approved:'||new.id;
  v_payload:=jsonb_build_object('task_id',new.id,'project_id',new.project_id,'member_id',new.assignee_id,
    'verifier_id',new.verifier_id,'title',new.title,'xp',v_xp,'xp_breakdown',v_breakdown,
    'ledger_ids',v_ledger_ids,'season',extract(year from(new.completed_at at time zone 'UTC'))::integer);
  insert into public.notifications(member_id,type,event_key,payload)
  values(new.assignee_id,'task_approved',v_key,v_payload) on conflict(member_id,event_key) do nothing;
  insert into public.news(chapter_id,type,member_id,project_id,text,event_key)
  values(new.chapter_id,'task_approved',new.assignee_id,new.project_id,
    v_name||' completed “'||new.title||'” and earned '||v_xp||' XP.',v_key)
  on conflict(event_key) do nothing;
  return new;
end $$;
drop trigger if exists zz_jaybird_task_approved on public.tasks;
create trigger zz_jaybird_task_approved after update of status on public.tasks
for each row execute function public.jaybird_on_task_approved();

