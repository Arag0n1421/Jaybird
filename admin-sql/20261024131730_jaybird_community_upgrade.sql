create or replace function public.set_follow(p_follower bigint,p_followee bigint,p_follow boolean)
returns boolean language plpgsql security invoker set search_path=public,pg_temp as $$
begin
  if p_follower is null or p_followee is null or p_follow is null then
    raise exception 'Follower, followee and follow state are required' using errcode='22023';
  end if;
  if p_follower=p_followee then raise exception 'You cannot follow yourself' using errcode='22023'; end if;
  if p_follow then
    insert into public.follows(follower_id,followee_id) values(p_follower,p_followee) on conflict do nothing;
  else
    delete from public.follows where follower_id=p_follower and followee_id=p_followee;
  end if;
  return p_follow;
end $$;

-- Lock the project row so a close cannot race a successful new join.
-- This also protects direct INSERT/UPDATE, not only the RPC path.
create or replace function public.jaybird_guard_project_join()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_status text;
begin
  select status into v_status from public.projects where id=new.project_id for share;
  if not found then raise exception 'Project does not exist' using errcode='23503'; end if;
  if v_status='closed' then raise exception 'This project is closed to new joins' using errcode='23514'; end if;
  return new;
end $$;
drop trigger if exists jaybird_guard_project_join on public.project_members;
create trigger jaybird_guard_project_join before insert or update of project_id,member_id
on public.project_members for each row execute function public.jaybird_guard_project_join();

create or replace function public.join_project(p_project bigint,p_member bigint)
returns boolean language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_status text;
begin
  if p_project is null or p_member is null then raise exception 'Project and member are required' using errcode='22023'; end if;
  select status into v_status from public.projects where id=p_project for share;
  if not found then raise exception 'Project does not exist' using errcode='23503'; end if;
  -- An already joined member remains joined after the project closes.
  if exists(select 1 from public.project_members where project_id=p_project and member_id=p_member) then return true; end if;
  if v_status='closed' then raise exception 'This project is closed to new joins' using errcode='23514'; end if;
  insert into public.project_members(project_id,member_id) values(p_project,p_member) on conflict do nothing;
  return true;
end $$;

